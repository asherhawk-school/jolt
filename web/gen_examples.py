#!/usr/bin/env python3
"""Bundle selected test programs as playground examples (examples.js)."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROGRAMS = os.path.join(ROOT, "tests", "programs")

EXAMPLES = [
    ("Welcome", "Welcome tour"),
    ("Mandelbrot", "Mandelbrot set (ASCII art)"),
    ("Life", "Game of Life"),
    ("Algorithms", "Algorithms: sorting, DP, N-queens"),
    ("Shapes", "Classes, interfaces, inheritance"),
    ("Strings", "Strings, StringBuilder, printf"),
    ("Exceptions", "Exceptions and try/catch"),
    ("Input", "Reading input with Scanner"),
    ("Switches", "Switch statements"),
    ("Tricky", "Edge cases: overloading, NaN, varargs"),
    ("Uncaught", "An uncaught exception"),
]

out = []
for name, title in EXAMPLES:
    with open(os.path.join(PROGRAMS, name + ".java")) as f:
        code = f.read()
    stdin_path = os.path.join(PROGRAMS, name + ".in")
    stdin = open(stdin_path).read() if os.path.exists(stdin_path) else ""
    out.append({"id": name, "title": title, "code": code, "input": stdin})

print("// Generated by web/gen_examples.py from tests/programs. Do not edit.")
print("window.JOLT_EXAMPLES = " + json.dumps(out, indent=1) + ";")
